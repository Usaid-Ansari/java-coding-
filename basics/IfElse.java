public class IfElse {
    public static void main(String[] args) {
    // If-Else Syntax
    // if(true or false ) {
    //     // do this
    // } else{
    //     // do this 
    // }
    int salary = 25400;
    if(salary > 10000){
        salary = salary + 2000;
    } else {
        salary = salary + 1000;
    }
    System.out.println(salary);
    }
}
